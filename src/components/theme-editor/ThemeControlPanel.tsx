import { useState, useRef } from 'react'
import {
  RotateCcw,
  Shuffle,
  BookmarkPlus,
  Download,
  Upload,
  Undo2,
  Eye,
  AlertTriangle,
  Wand2,
  Check,
  ChevronDown,
} from 'lucide-react'
import { useTheme } from '@/context/useTheme'
import {
  BACKGROUND_PRESETS,
  ACCENT_PRESETS,
  MOOD_PALETTES,
  CHART_PALETTES,
} from '@/lib/themePresets'
import { HEADING_FONTS, BODY_FONTS } from '@/lib/fontLoader'
import {
  autoFixTextColor,
  generateDarkPaletteFromLight,
  getAccentContrast,
  isContrastAdequate,
  getContrastRatio,
} from '@/lib/colorUtils'
import { exportThemeToJson, validateAndParseThemeJson } from '@/lib/themeEngine'
import ColorPickerPopover from './ColorPickerPopover'
import FontPickerPopover from './FontPickerPopover'
import type {
  AnimationLevel,
  BorderLevel,
  DensityLevel,
  IconLibrary,
  RadiusLevel,
  ShadowLevel,
  ThemeColorMode,
} from '@/types/theme'

export default function ThemeControlPanel() {
  const {
    customConfig,
    updateCustomConfig,
    isDark,
    setIsDark,
    resetToDefault,
    shuffleTheme,
    undo,
    canUndo,
    setIsComparing,
    saveCurrentAsPreset,
  } = useTheme()

  const colors = isDark ? customConfig.dark : customConfig.light

  // Popover state
  const [activePopover, setActivePopover] = useState<string | null>(null)
  const [saveNamePrompt, setSaveNamePrompt] = useState(false)
  const [saveName, setSaveName] = useState('')
  const [importError, setImportError] = useState<string | null>(null)
  const fileInputRef = useRef<HTMLInputElement | null>(null)

  // Color contrast check
  const surfaceContrastOk = isContrastAdequate(colors.surface, colors.text, 4.5)
  const bgContrastOk = isContrastAdequate(colors.bg, colors.text, 4.5)
  const contrastRatio = getContrastRatio(colors.surface, colors.text).toFixed(1)

  const handleUpdateColors = (partial: Partial<typeof colors>) => {
    updateCustomConfig((prev) => {
      if (isDark) {
        return { ...prev, dark: { ...prev.dark, ...partial } }
      } else {
        return { ...prev, light: { ...prev.light, ...partial } }
      }
    })
  }

  const handleAutoFixContrast = () => {
    const fixedText = autoFixTextColor(colors.surface, colors.text)
    const fixedTextMuted = autoFixTextColor(colors.surface, isDark ? '#A8A097' : '#7A736B')
    handleUpdateColors({ text: fixedText, textMuted: fixedTextMuted })
  }

  const handleAutoGenerateDark = () => {
    const darkPalette = generateDarkPaletteFromLight(
      customConfig.light.bg,
      customConfig.light.surface,
    )
    updateCustomConfig((prev) => ({
      ...prev,
      dark: {
        ...prev.dark,
        ...darkPalette,
        accent: prev.light.accent,
        accentContrast: getAccentContrast(prev.light.accent),
      },
    }))
  }

  const handleImportJson = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0]
    if (!file) return
    const reader = new FileReader()
    reader.onload = (event) => {
      try {
        const content = event.target?.result as string
        const parsed = validateAndParseThemeJson(content)
        updateCustomConfig(parsed)
        setImportError(null)
      } catch (err: unknown) {
        setImportError(err instanceof Error ? err.message : 'Tệp JSON không hợp lệ')
      }
    }
    reader.readAsText(file)
  }

  return (
    <div className="flex h-full flex-col justify-between overflow-y-auto p-4 text-[var(--text)] select-none">
      <div className="space-y-4">
        {/* Contrast Warning Banner if < 4.5:1 */}
        {(!surfaceContrastOk || !bgContrastOk) && (
          <div className="flex items-center justify-between rounded-xl border border-amber-500/30 bg-amber-500/10 p-2.5 text-xs text-amber-600 dark:text-amber-400 animate-in fade-in">
            <div className="flex items-center gap-1.5">
              <AlertTriangle size={15} className="shrink-0" />
              <span>
                Độ tương phản thấp ({contrastRatio}:1)
              </span>
            </div>
            <button
              type="button"
              onClick={handleAutoFixContrast}
              className="flex items-center gap-1 rounded-lg bg-amber-500/20 px-2 py-1 font-semibold text-amber-700 dark:text-amber-300 hover:bg-amber-500/30 transition-colors"
            >
              <Wand2 size={12} /> Tự sửa
            </button>
          </div>
        )}

        {/* Import Error Message */}
        {importError && (
          <div className="rounded-xl border border-rose-500/30 bg-rose-500/10 p-2.5 text-xs text-rose-600 dark:text-rose-400">
            {importError}
          </div>
        )}

        {/* 14. Chế độ Sáng / Tối */}
        <div className="flex items-center justify-between border-b border-[var(--border)] pb-3">
          <label className="text-xs font-semibold text-[var(--text-muted)] uppercase tracking-wider">
            Chế độ màu
          </label>
          <div className="flex items-center gap-1 rounded-xl bg-[var(--surface-2)] p-1 border border-[var(--border)]">
            {(['light', 'dark', 'system'] as ThemeColorMode[]).map((mode) => (
              <button
                key={mode}
                type="button"
                onClick={() => {
                  if (mode === 'system') {
                    const systemDark = window.matchMedia('(prefers-color-scheme: dark)').matches
                    setIsDark(systemDark)
                  } else {
                    setIsDark(mode === 'dark')
                  }
                  updateCustomConfig({ colorMode: mode })
                }}
                className={`rounded-lg px-2.5 py-1 text-xs font-medium transition-all ${
                  customConfig.colorMode === mode
                    ? 'bg-[var(--surface)] text-[var(--text)] shadow-xs'
                    : 'text-[var(--text-muted)] hover:text-[var(--text)]'
                }`}
              >
                {mode === 'light' ? '☀️ Sáng' : mode === 'dark' ? '🌙 Tối' : '💻 Tự động'}
              </button>
            ))}
          </div>
        </div>

        {/* 1. Màu Nền (Background) */}
        <div className="relative flex items-center justify-between">
          <div>
            <p className="text-xs font-semibold text-[var(--text)]">Màu nền trang</p>
            <p className="text-[11px] text-[var(--text-muted)] font-mono">{colors.bg}</p>
          </div>
          <button
            type="button"
            onClick={() => setActivePopover(activePopover === 'bg' ? null : 'bg')}
            className="flex items-center gap-1.5 rounded-xl border border-[var(--border)] bg-[var(--surface)] p-1.5 pr-2.5 shadow-xs"
          >
            <span
              className="size-5 rounded-lg border border-[var(--border)]"
              style={{ backgroundColor: colors.bg }}
            />
            <ChevronDown size={13} className="text-[var(--text-muted)]" />
          </button>
          {activePopover === 'bg' && (
            <ColorPickerPopover
              label="Chọn màu nền"
              color={colors.bg}
              presets={BACKGROUND_PRESETS.map((p) => ({
                name: p.name,
                hex: isDark ? p.darkHex : p.hex,
              }))}
              onChange={(hex) => handleUpdateColors({ bg: hex })}
              onClose={() => setActivePopover(null)}
            />
          )}
        </div>

        {/* 2. Màu Nhấn (Accent) */}
        <div className="relative flex items-center justify-between">
          <div>
            <p className="text-xs font-semibold text-[var(--text)]">Màu nhấn chính (Accent)</p>
            <p className="text-[11px] text-[var(--text-muted)] font-mono">{colors.accent}</p>
          </div>
          <button
            type="button"
            onClick={() => setActivePopover(activePopover === 'accent' ? null : 'accent')}
            className="flex items-center gap-1.5 rounded-xl border border-[var(--border)] bg-[var(--surface)] p-1.5 pr-2.5 shadow-xs"
          >
            <span
              className="size-5 rounded-lg border border-[var(--border)]"
              style={{ backgroundColor: colors.accent }}
            />
            <ChevronDown size={13} className="text-[var(--text-muted)]" />
          </button>
          {activePopover === 'accent' && (
            <ColorPickerPopover
              label="Chọn màu nhấn"
              color={colors.accent}
              presets={ACCENT_PRESETS}
              onChange={(hex) =>
                handleUpdateColors({
                  accent: hex,
                  accentContrast: getAccentContrast(hex),
                })
              }
              onClose={() => setActivePopover(null)}
            />
          )}
        </div>

        {/* 3. Màu Thẻ & Màu Chữ */}
        <div className="grid grid-cols-2 gap-2">
          {/* Surface */}
          <div className="relative rounded-2xl border border-[var(--border)] bg-[var(--surface-2)] p-2.5">
            <p className="text-[11px] font-semibold text-[var(--text-muted)]">Màu thẻ (Surface)</p>
            <button
              type="button"
              onClick={() => setActivePopover(activePopover === 'surface' ? null : 'surface')}
              className="mt-1 flex w-full items-center justify-between rounded-xl border border-[var(--border)] bg-[var(--surface)] p-1.5"
            >
              <span
                className="size-4 rounded-md border border-[var(--border)]"
                style={{ backgroundColor: colors.surface }}
              />
              <span className="font-mono text-[10px] text-[var(--text)]">{colors.surface}</span>
            </button>
            {activePopover === 'surface' && (
              <ColorPickerPopover
                label="Chọn màu thẻ"
                color={colors.surface}
                onChange={(hex) => handleUpdateColors({ surface: hex })}
                onClose={() => setActivePopover(null)}
              />
            )}
          </div>

          {/* Text Color */}
          <div className="relative rounded-2xl border border-[var(--border)] bg-[var(--surface-2)] p-2.5">
            <p className="text-[11px] font-semibold text-[var(--text-muted)]">Màu chữ (Text)</p>
            <button
              type="button"
              onClick={() => setActivePopover(activePopover === 'text' ? null : 'text')}
              className="mt-1 flex w-full items-center justify-between rounded-xl border border-[var(--border)] bg-[var(--surface)] p-1.5"
            >
              <span
                className="size-4 rounded-md border border-[var(--border)]"
                style={{ backgroundColor: colors.text }}
              />
              <span className="font-mono text-[10px] text-[var(--text)]">{colors.text}</span>
            </button>
            {activePopover === 'text' && (
              <ColorPickerPopover
                label="Chọn màu chữ"
                color={colors.text}
                onChange={(hex) => handleUpdateColors({ text: hex })}
                onClose={() => setActivePopover(null)}
              />
            )}
          </div>
        </div>

        {/* Tự sinh bản tối nếu đang ở chế độ sáng */}
        {!isDark && (
          <button
            type="button"
            onClick={handleAutoGenerateDark}
            className="flex w-full items-center justify-center gap-1.5 rounded-xl border border-dashed border-[var(--border)] py-1.5 text-xs text-[var(--text-muted)] hover:border-solid hover:bg-[var(--surface-2)] hover:text-[var(--text)] transition-all"
          >
            <Wand2 size={13} /> Tự sinh bản Dark mode từ bảng màu này
          </button>
        )}

        {/* 4. Bộ màu Mood 1-5 */}
        <div className="space-y-2">
          <div className="flex items-center justify-between">
            <p className="text-xs font-semibold text-[var(--text)]">Bộ màu Mood (1—5)</p>
            <span className="text-[10px] text-[var(--text-muted)]">5 mức cảm xúc</span>
          </div>
          {/* Palette presets */}
          <div className="grid grid-cols-2 gap-1.5">
            {MOOD_PALETTES.map((pal) => (
              <button
                key={pal.name}
                type="button"
                onClick={() => handleUpdateColors({ mood: pal.colors })}
                className="flex flex-col gap-1 rounded-xl border border-[var(--border)] bg-[var(--surface-2)] p-1.5 text-left hover:border-[var(--accent)] transition-all"
              >
                <div className="flex h-3 w-full overflow-hidden rounded-md">
                  {pal.colors.map((c, i) => (
                    <span key={i} className="flex-1" style={{ backgroundColor: c }} />
                  ))}
                </div>
                <span className="truncate text-[10px] font-medium text-[var(--text-muted)]">
                  {pal.name}
                </span>
              </button>
            ))}
          </div>
        </div>

        {/* 5. Màu Biểu đồ */}
        <div className="space-y-2">
          <p className="text-xs font-semibold text-[var(--text)]">Màu Biểu đồ Thống kê</p>
          <div className="grid grid-cols-2 gap-1.5">
            {CHART_PALETTES.map((pal) => (
              <button
                key={pal.name}
                type="button"
                onClick={() => handleUpdateColors({ chart: pal.colors })}
                className="flex flex-col gap-1 rounded-xl border border-[var(--border)] bg-[var(--surface-2)] p-1.5 text-left hover:border-[var(--accent)] transition-all"
              >
                <div className="flex h-3 w-full overflow-hidden rounded-md">
                  {pal.colors.map((c, i) => (
                    <span key={i} className="flex-1" style={{ backgroundColor: c }} />
                  ))}
                </div>
                <span className="truncate text-[10px] font-medium text-[var(--text-muted)]">
                  {pal.name}
                </span>
              </button>
            ))}
          </div>
        </div>

        {/* 6. Font Tiêu đề */}
        <div className="relative flex items-center justify-between">
          <div>
            <p className="text-xs font-semibold text-[var(--text)]">Font Tiêu đề</p>
            <p className="text-[11px] text-[var(--text-muted)] truncate max-w-[170px]">
              {HEADING_FONTS.find((f) => f.family === customConfig.fontHeading)?.name ||
                customConfig.fontHeading}
            </p>
          </div>
          <button
            type="button"
            onClick={() => setActivePopover(activePopover === 'fontHead' ? null : 'fontHead')}
            className="flex items-center gap-1.5 rounded-xl border border-[var(--border)] bg-[var(--surface)] px-2.5 py-1.5 text-xs font-bold text-[var(--text)] shadow-xs"
          >
            <span>Aa</span>
            <ChevronDown size={13} className="text-[var(--text-muted)]" />
          </button>
          {activePopover === 'fontHead' && (
            <FontPickerPopover
              label="Chọn font tiêu đề"
              currentFamily={customConfig.fontHeading}
              fonts={HEADING_FONTS}
              onChange={(fam) => updateCustomConfig({ fontHeading: fam })}
              onClose={() => setActivePopover(null)}
            />
          )}
        </div>

        {/* 7. Font Nội dung */}
        <div className="relative flex items-center justify-between">
          <div>
            <p className="text-xs font-semibold text-[var(--text)]">Font Nội dung (Tiếng Việt)</p>
            <p className="text-[11px] text-[var(--text-muted)] truncate max-w-[170px]">
              {BODY_FONTS.find((f) => f.family === customConfig.fontBody)?.name ||
                customConfig.fontBody}
            </p>
          </div>
          <button
            type="button"
            onClick={() => setActivePopover(activePopover === 'fontBody' ? null : 'fontBody')}
            className="flex items-center gap-1.5 rounded-xl border border-[var(--border)] bg-[var(--surface)] px-2.5 py-1.5 text-xs font-bold text-[var(--text)] shadow-xs"
          >
            <span>Aa</span>
            <ChevronDown size={13} className="text-[var(--text-muted)]" />
          </button>
          {activePopover === 'fontBody' && (
            <FontPickerPopover
              label="Chọn font nội dung"
              currentFamily={customConfig.fontBody}
              fonts={BODY_FONTS}
              filterVietnameseOnly
              onChange={(fam) => updateCustomConfig({ fontBody: fam })}
              onClose={() => setActivePopover(null)}
            />
          )}
        </div>

        {/* 8. Cỡ chữ gốc & Độ giãn dòng */}
        <div className="space-y-3 rounded-2xl border border-[var(--border)] bg-[var(--surface-2)] p-3">
          <div>
            <div className="flex justify-between text-xs font-semibold">
              <span className="text-[var(--text)]">Cỡ chữ gốc</span>
              <span className="font-mono text-[var(--text-muted)]">
                {customConfig.fontSizeBase}px
              </span>
            </div>
            <input
              type="range"
              min={14}
              max={20}
              value={customConfig.fontSizeBase}
              onChange={(e) => updateCustomConfig({ fontSizeBase: Number(e.target.value) })}
              className="mt-1 h-2 w-full appearance-none rounded-lg bg-[var(--surface)] cursor-pointer"
            />
          </div>

          <div>
            <div className="flex justify-between text-xs font-semibold">
              <span className="text-[var(--text)]">Độ giãn dòng (Line height)</span>
              <span className="font-mono text-[var(--text-muted)]">
                {customConfig.lineHeight.toFixed(1)}
              </span>
            </div>
            <input
              type="range"
              min={1.4}
              max={1.9}
              step={0.05}
              value={customConfig.lineHeight}
              onChange={(e) => updateCustomConfig({ lineHeight: Number(e.target.value) })}
              className="mt-1 h-2 w-full appearance-none rounded-lg bg-[var(--surface)] cursor-pointer"
            />
          </div>
        </div>

        {/* 9. Bo góc (Radius) */}
        <div>
          <p className="mb-1.5 text-xs font-semibold text-[var(--text)]">Độ bo góc (Radius)</p>
          <div className="grid grid-cols-5 gap-1">
            {(
              [
                ['square', 'Vuông'],
                ['small', 'Nhẹ'],
                ['medium', 'Vừa'],
                ['large', 'Lớn'],
                ['full', 'Tròn'],
              ] as [RadiusLevel, string][]
            ).map(([lvl, label]) => (
              <button
                key={lvl}
                type="button"
                onClick={() => updateCustomConfig({ radius: lvl })}
                className={`rounded-xl py-1 text-center text-xs font-medium border transition-all ${
                  customConfig.radius === lvl
                    ? 'border-[var(--accent)] bg-[var(--surface)] font-bold text-[var(--text)] shadow-xs'
                    : 'border-[var(--border)] text-[var(--text-muted)] hover:text-[var(--text)]'
                }`}
              >
                {label}
              </button>
            ))}
          </div>
        </div>

        {/* 10. Kiểu Viền & Bóng */}
        <div className="grid grid-cols-2 gap-2">
          {/* Viền */}
          <div>
            <p className="mb-1 text-xs font-semibold text-[var(--text)]">Kiểu viền</p>
            <div className="flex flex-col gap-1">
              {(
                [
                  ['none', 'Không viền'],
                  ['thin', 'Viền mảnh'],
                  ['hand-drawn', 'Viền đậm'],
                ] as [BorderLevel, string][]
              ).map(([lvl, label]) => (
                <button
                  key={lvl}
                  type="button"
                  onClick={() => updateCustomConfig({ borderStyle: lvl })}
                  className={`rounded-xl py-1 px-2 text-left text-xs font-medium border transition-all ${
                    customConfig.borderStyle === lvl
                      ? 'border-[var(--accent)] bg-[var(--surface)] font-bold text-[var(--text)]'
                      : 'border-[var(--border)] text-[var(--text-muted)] hover:text-[var(--text)]'
                  }`}
                >
                  {label}
                </button>
              ))}
            </div>
          </div>

          {/* Bóng */}
          <div>
            <p className="mb-1 text-xs font-semibold text-[var(--text)]">Kiểu bóng đổ</p>
            <div className="flex flex-col gap-1">
              {(
                [
                  ['none', 'Phẳng'],
                  ['soft', 'Mềm dịu'],
                  ['retro-hard', 'Bóng cứng'],
                ] as [ShadowLevel, string][]
              ).map(([lvl, label]) => (
                <button
                  key={lvl}
                  type="button"
                  onClick={() => updateCustomConfig({ shadowStyle: lvl })}
                  className={`rounded-xl py-1 px-2 text-left text-xs font-medium border transition-all ${
                    customConfig.shadowStyle === lvl
                      ? 'border-[var(--accent)] bg-[var(--surface)] font-bold text-[var(--text)]'
                      : 'border-[var(--border)] text-[var(--text-muted)] hover:text-[var(--text)]'
                  }`}
                >
                  {label}
                </button>
              ))}
            </div>
          </div>
        </div>

        {/* 11. Mật độ (Density) & 12. Hoạt ảnh (Animation) */}
        <div className="grid grid-cols-2 gap-2">
          {/* Mật độ */}
          <div>
            <p className="mb-1 text-xs font-semibold text-[var(--text)]">Mật độ (Density)</p>
            <div className="flex flex-col gap-1">
              {(
                [
                  ['compact', 'Gọn'],
                  ['normal', 'Vừa'],
                  ['spacious', 'Thoáng'],
                ] as [DensityLevel, string][]
              ).map(([lvl, label]) => (
                <button
                  key={lvl}
                  type="button"
                  onClick={() => updateCustomConfig({ density: lvl })}
                  className={`rounded-xl py-1 px-2 text-left text-xs font-medium border transition-all ${
                    customConfig.density === lvl
                      ? 'border-[var(--accent)] bg-[var(--surface)] font-bold text-[var(--text)]'
                      : 'border-[var(--border)] text-[var(--text-muted)] hover:text-[var(--text)]'
                  }`}
                >
                  {label}
                </button>
              ))}
            </div>
          </div>

          {/* Hoạt ảnh */}
          <div>
            <p className="mb-1 text-xs font-semibold text-[var(--text)]">Hoạt ảnh</p>
            <div className="flex flex-col gap-1">
              {(
                [
                  ['none', 'Tắt'],
                  ['subtle', 'Nhẹ'],
                  ['playful', 'Vui nảy'],
                ] as [AnimationLevel, string][]
              ).map(([lvl, label]) => (
                <button
                  key={lvl}
                  type="button"
                  onClick={() => updateCustomConfig({ animation: lvl })}
                  className={`rounded-xl py-1 px-2 text-left text-xs font-medium border transition-all ${
                    customConfig.animation === lvl
                      ? 'border-[var(--accent)] bg-[var(--surface)] font-bold text-[var(--text)]'
                      : 'border-[var(--border)] text-[var(--text-muted)] hover:text-[var(--text)]'
                  }`}
                >
                  {label}
                </button>
              ))}
            </div>
          </div>
        </div>

        {/* 13. Thư viện Icon */}
        <div>
          <p className="mb-1.5 text-xs font-semibold text-[var(--text)]">Thư viện Icon</p>
          <div className="grid grid-cols-3 gap-1">
            {(
              [
                ['lucide', 'Lucide'],
                ['phosphor', 'Phosphor'],
                ['doodle', 'Vẽ tay ✿'],
              ] as [IconLibrary, string][]
            ).map(([lvl, label]) => (
              <button
                key={lvl}
                type="button"
                onClick={() => updateCustomConfig({ iconLibrary: lvl })}
                className={`rounded-xl py-1 text-center text-xs font-medium border transition-all ${
                  customConfig.iconLibrary === lvl
                    ? 'border-[var(--accent)] bg-[var(--surface)] font-bold text-[var(--text)] shadow-xs'
                    : 'border-[var(--border)] text-[var(--text-muted)] hover:text-[var(--text)]'
                }`}
              >
                {label}
              </button>
            ))}
          </div>
        </div>
      </div>

      {/* CÁC NÚT HÀNH ĐỘNG DƯỚI CÙNG */}
      <div className="mt-6 space-y-2 border-t border-[var(--border)] pt-4">
        {/* Undo and Compare buttons */}
        <div className="flex items-center gap-2">
          <button
            type="button"
            disabled={!canUndo}
            onClick={undo}
            className="flex flex-1 items-center justify-center gap-1.5 rounded-xl border border-[var(--border)] bg-[var(--surface)] py-2 text-xs font-semibold text-[var(--text)] hover:bg-[var(--surface-2)] disabled:opacity-40"
          >
            <Undo2 size={13} /> Hoàn tác (Ctrl+Z)
          </button>
          <button
            type="button"
            onMouseDown={() => setIsComparing(true)}
            onMouseUp={() => setIsComparing(false)}
            onMouseLeave={() => setIsComparing(false)}
            onTouchStart={() => setIsComparing(true)}
            onTouchEnd={() => setIsComparing(false)}
            className="flex flex-1 items-center justify-center gap-1.5 rounded-xl border border-[var(--border)] bg-[var(--surface)] py-2 text-xs font-semibold text-[var(--text)] active:bg-[var(--accent)] active:text-[var(--accent-contrast)]"
          >
            <Eye size={13} /> Giữ để so sánh
          </button>
        </div>

        {/* Shuffle & Reset */}
        <div className="flex items-center gap-2">
          <button
            type="button"
            onClick={shuffleTheme}
            className="flex flex-1 items-center justify-center gap-1.5 rounded-xl border border-[var(--border)] bg-[var(--surface-2)] py-2 text-xs font-semibold text-[var(--text)] hover:bg-[var(--surface)]"
          >
            <Shuffle size={13} /> Xáo trộn
          </button>
          <button
            type="button"
            onClick={resetToDefault}
            className="flex flex-1 items-center justify-center gap-1.5 rounded-xl border border-[var(--border)] bg-[var(--surface-2)] py-2 text-xs font-semibold text-[var(--text-muted)] hover:text-[var(--text)]"
          >
            <RotateCcw size={13} /> Đặt lại
          </button>
        </div>

        {/* Save as preset prompt */}
        {saveNamePrompt ? (
          <div className="flex items-center gap-1.5">
            <input
              type="text"
              value={saveName}
              onChange={(e) => setSaveName(e.target.value)}
              placeholder="Đặt tên bộ theme..."
              className="h-8 flex-1 rounded-xl border border-[var(--border)] bg-[var(--surface)] px-2.5 text-xs text-[var(--text)] outline-none"
            />
            <button
              type="button"
              onClick={() => {
                saveCurrentAsPreset(saveName)
                setSaveNamePrompt(false)
                setSaveName('')
              }}
              className="flex size-8 items-center justify-center rounded-xl bg-[var(--accent)] text-[var(--accent-contrast)] shadow-xs"
            >
              <Check size={14} />
            </button>
          </div>
        ) : (
          <button
            type="button"
            onClick={() => setSaveNamePrompt(true)}
            className="flex w-full items-center justify-center gap-1.5 rounded-xl border border-[var(--border-strong)] bg-[var(--accent)] py-2 text-xs font-semibold text-[var(--accent-contrast)] shadow-xs hover:opacity-90"
          >
            <BookmarkPlus size={14} /> Lưu thành bộ riêng
          </button>
        )}

        {/* Export / Import JSON */}
        <div className="flex items-center gap-2 pt-1">
          <button
            type="button"
            onClick={() => exportThemeToJson(customConfig)}
            className="flex flex-1 items-center justify-center gap-1.5 rounded-xl border border-[var(--border)] bg-[var(--surface)] py-1.5 text-[11px] font-medium text-[var(--text)] hover:bg-[var(--surface-2)]"
          >
            <Download size={12} /> Xuất JSON
          </button>
          <button
            type="button"
            onClick={() => fileInputRef.current?.click()}
            className="flex flex-1 items-center justify-center gap-1.5 rounded-xl border border-[var(--border)] bg-[var(--surface)] py-1.5 text-[11px] font-medium text-[var(--text)] hover:bg-[var(--surface-2)]"
          >
            <Upload size={12} /> Nhập JSON
          </button>
          <input
            ref={fileInputRef}
            type="file"
            accept=".json,application/json"
            onChange={handleImportJson}
            className="hidden"
          />
        </div>
      </div>
    </div>
  )
}
